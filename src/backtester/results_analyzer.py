import logging
import os
import sys
from pathlib import Path
from typing import Any, Optional

import numpy as np
import pandas as pd

from .trade_analyzer import TradeAnalyzer
from .trade_chart_report import TradeChartReportConfig, build_trade_chart_report
from .visualizer import TradeConditionsVisualizer


class ResultsAnalyzer:
    """
    Class for analyzing the results of a trading strategy backtest.

    Accepts a DataFrame with trade history (from ExecutionSim) and generates:
    - Summary metrics: Win Rate, PnL, Profit Factor, Max Drawdown, etc.
    - Periodic returns (daily/weekly/monthly)
    - Trade distribution by exit reasons (TP / SL / TTL / final)
    - Capital curve
    - Text reports and CSV files

    Key Features:
    -------------
    - Support for long and short positions
    - Automatic time period calculation
    - Max Drawdown computation
    - Data export to files
    - Data preparation for visualization

    Usage Example:
    --------------
    >>> analyzer = ResultsAnalyzer(trades_df)
    >>> metrics = analyzer.generate()
    >>> analyzer.print_report()
    >>> analyzer.export_results("results/strategy_v1")
    """

    def __init__(self, trades_df: pd.DataFrame, signal_df: pd.DataFrame | None = None):
        """
        Initializes the analyzer.

        Parameters:
        -----------
        trades_df : pd.DataFrame
            Table of trades generated by ExecutionSim.run().
            Required columns:
            - entry_time: datetime - entry time
            - exit_time: datetime - exit time
            - entry_price: float - entry price
            - exit_price: float - exit price
            - pnl_abs: float - profit/loss in money
            - pnl_rel: float - relative profit
            - exit_reason: str - exit reason ('take_profit', 'stop_loss', etc.)
            - capital_before: float - capital before entry
            - capital_after: float - capital after exit
            - holding_bars: int - trade duration in bars
            - is_long: bool - True for long, False for short
        Internal Attributes:
        --------------------
        self.trades : pd.DataFrame
            Copy of input DataFrame with added time columns.
        self.equity_curve : pd.Series or None
            Capital curve (index: exit time, value: capital).
        self.metrics : dict
            Dictionary of metrics, populated after .generate().

        Notes:
        ------
        - If trades_df is empty, the analyzer will handle this and return an error.
        - All timestamps are converted to pd.Timestamp.
        - Data is sorted by exit time for accurate equity curve calculation.
        """
        self.trades = trades_df.copy() if not trades_df.empty else pd.DataFrame()
        self.signals = signal_df.copy() if signal_df is not None else pd.DataFrame()
        self.equity_curve: pd.Series | None = None
        self.metrics: dict[str, Any] = {}
        self.trade_analyzer: Optional[TradeAnalyzer] = None
        self.visualizer: Optional[TradeConditionsVisualizer] = None
        self._logger = logging.getLogger(__name__)

    def _prepare_trades_df(self) -> pd.DataFrame:
        """Prepare and normalize trades dataframe for metric computations."""
        df = self.trades.copy()
        df["exit_time"] = pd.to_datetime(df["exit_time"], errors="coerce")
        df["entry_time"] = pd.to_datetime(df["entry_time"])
        df.sort_values("exit_time", inplace=True)

        # Period columns for aggregations
        df["date"] = df["exit_time"].dt.date
        df["week"] = df["exit_time"].dt.to_period("W")
        df["month"] = df["exit_time"].dt.to_period("M")
        return df

    @staticmethod
    def _closed_trades_df(df: pd.DataFrame) -> pd.DataFrame:
        """Return trades with realized exits for PnL/equity metrics."""
        if df.empty or "exit_reason" not in df.columns:
            return df
        closed = df[df["exit_reason"] != "open"].copy()
        if "exit_time" in closed.columns:
            closed = closed.dropna(subset=["exit_time"])
        return closed

    @staticmethod
    def _compute_basic_metrics(df: pd.DataFrame) -> dict[str, Any]:
        """Compute basic aggregate metrics for a trade subset."""
        total_trades = int(len(df))
        if total_trades == 0:
            return {
                "total_trades": 0,
                "win_rate": 0.0,  # fraction (0..1)
                "total_pnl_abs": 0.0,
                "avg_pnl_abs": 0.0,
                "avg_win": 0.0,
                "avg_loss": 0.0,
                "profit_factor": float("inf"),
            }

        winning_trades = df[df["pnl_abs"] > 0]
        losing_trades = df[df["pnl_abs"] < 0]

        win_rate = len(winning_trades) / total_trades if total_trades != 0 else 0.0
        total_pnl_abs = float(df["pnl_abs"].sum())
        avg_pnl_abs = float(df["pnl_abs"].mean())
        avg_win = float(winning_trades["pnl_abs"].mean()) if len(winning_trades) != 0 else 0.0
        avg_loss = float(losing_trades["pnl_abs"].mean()) if len(losing_trades) != 0 else 0.0

        profit_factor = (
            abs(winning_trades["pnl_abs"].sum() / losing_trades["pnl_abs"].sum())
            if len(losing_trades) != 0 and losing_trades["pnl_abs"].sum() != 0
            else float("inf")
        )

        return {
            "total_trades": total_trades,
            "win_rate": float(win_rate),
            "total_pnl_abs": total_pnl_abs,
            "avg_pnl_abs": avg_pnl_abs,
            "avg_win": avg_win,
            "avg_loss": avg_loss,
            "profit_factor": float(profit_factor),
        }

    @staticmethod
    def _compute_period_pnl_means(df: pd.DataFrame) -> dict[str, float]:
        """Compute mean PnL aggregated by date/week/month."""
        daily_pnl = df.groupby("date")["pnl_abs"].sum()
        weekly_pnl = df.groupby("week")["pnl_abs"].sum()
        monthly_pnl = df.groupby("month")["pnl_abs"].sum()

        return {
            "daily_pnl_mean": float(daily_pnl.mean()) if len(daily_pnl) else 0.0,
            "weekly_pnl_mean": float(weekly_pnl.mean()) if len(weekly_pnl) else 0.0,
            "monthly_pnl_mean": float(monthly_pnl.mean()) if len(monthly_pnl) else 0.0,
        }

    @staticmethod
    def _compute_exit_distribution(df: pd.DataFrame) -> dict[str, int]:
        """Compute distribution of exit reasons."""
        return df["exit_reason"].value_counts().to_dict()

    def _compute_equity_curve(self, df: pd.DataFrame) -> tuple[pd.Series, float, float, float]:
        """Build equity curve and compute total return percentage."""
        equity = df[["exit_time", "capital_after"]].copy()
        equity.drop_duplicates(subset="exit_time", keep="last", inplace=True)
        equity.set_index("exit_time", inplace=True)
        equity.sort_index(inplace=True)
        self.equity_curve = equity["capital_after"]

        initial_capital: float = float(df.iloc[0]["capital_before"])
        final_capital = float(self.equity_curve.iloc[-1])
        total_return_pct = ((final_capital - initial_capital) / initial_capital) * 100
        return (
            self.equity_curve,
            initial_capital,
            final_capital,
            float(total_return_pct),
        )

    @staticmethod
    def _compute_drawdown_metrics(
        equity_curve: pd.Series, initial_capital: float
    ) -> dict[str, Any]:
        """Worst drawdown from window-start capital at closed-trade exit points."""
        if equity_curve.empty or initial_capital <= 0:
            return {"max_drawdown": 0.0}
        min_equity = min(float(initial_capital), float(equity_curve.min()))
        if min_equity >= initial_capital:
            return {"max_drawdown": 0.0}
        return {"max_drawdown": (min_equity - initial_capital) / initial_capital}

    @staticmethod
    def _compute_sharpe_ratio(
        equity_curve: pd.Series,
        initial_capital: float,
        risk_free_rate_annual: float = 0.02,
    ) -> float:
        """
        Compute annualized Sharpe ratio from monthly returns.

        SR = (MR - RFR) / SD per period, then annualized by sqrt(12).
        MR = mean monthly return, RFR = risk-free rate (monthly), SD = std of monthly returns.

        Parameters
        ----------
        equity_curve : pd.Series
            Capital curve (DatetimeIndex -> capital).
        initial_capital : float
            Starting capital.
        risk_free_rate_annual : float, optional
            Annual risk-free rate in decimal (e.g. 0.02 for 2%). Default 0.02.

        Returns
        -------
        float
            Annualized Sharpe ratio, or 0.0 if fewer than 2 months or SD is zero.
        """
        monthly_capital = equity_curve.resample("ME").last()
        if len(monthly_capital) < 2:
            return 0.0
        monthly_returns = monthly_capital.pct_change()
        monthly_returns.iloc[0] = (monthly_capital.iloc[0] - initial_capital) / initial_capital
        sd = float(monthly_returns.std())
        if sd == 0:
            return 0.0
        mr = float(monthly_returns.mean())
        rfr_monthly = (1 + risk_free_rate_annual) ** (1 / 12) - 1
        sr_monthly = (mr - rfr_monthly) / sd
        sr_annual = sr_monthly * np.sqrt(12)
        return round(float(sr_annual), 4)

    @staticmethod
    def _compute_monthly_returns_pct(
        equity_curve: pd.Series,
        initial_capital: float,
        trades_df: pd.DataFrame | None = None,
    ) -> dict[str, dict[str, float]]:
        """Compute monthly returns dict in the current output format."""
        monthly_capital = equity_curve.resample("ME").last()
        monthly_returns = monthly_capital.pct_change().fillna(0) * 100
        if len(monthly_capital) > 0:
            monthly_returns.iloc[0] = (
                (monthly_capital.iloc[0] - initial_capital) / initial_capital * 100
            )
        monthly_returns_abs = (monthly_capital - initial_capital) / initial_capital * 100
        monthly_withdrawals: dict[str, float] = {}
        if trades_df is not None and "capital_sweep_amount" in trades_df.columns:
            sweep = pd.to_numeric(trades_df["capital_sweep_amount"], errors="coerce").fillna(0.0)
            sweep_df = trades_df.loc[sweep.gt(0), ["exit_time"]].copy()
            if not sweep_df.empty:
                sweep_df["withdrawn"] = sweep.loc[sweep.gt(0)].values
                if "capital_sweep_month" in trades_df.columns:
                    sweep_month = trades_df.loc[sweep.gt(0), "capital_sweep_month"]
                    sweep_df["month"] = sweep_month.where(
                        sweep_month.notna(),
                        pd.to_datetime(sweep_df["exit_time"]).dt.strftime("%Y-%m"),
                    )
                else:
                    sweep_df["month"] = pd.to_datetime(sweep_df["exit_time"]).dt.strftime("%Y-%m")
                monthly_withdrawals = (
                    sweep_df.groupby("month")["withdrawn"].sum().round(2).to_dict()
                )

        rows = {
            str(period): {
                "ret": round(float(ret), 2),
                "ret_abs": round(float(ret_abs), 2),
                "withdrawn": round(float(monthly_withdrawals.get(str(period), 0.0)), 2),
            }
            for period, ret, ret_abs in zip(
                monthly_returns.index.strftime("%Y-%m"),
                monthly_returns.values,
                monthly_returns_abs.values,
                strict=False,
            )
        }
        for period, withdrawn in monthly_withdrawals.items():
            rows.setdefault(
                str(period),
                {
                    "ret": 0.0,
                    "ret_abs": 0.0,
                    "withdrawn": round(float(withdrawn), 2),
                },
            )
        return dict(sorted(rows.items()))

    @classmethod
    def _basic_metrics_for_subset(cls, sub_df: pd.DataFrame) -> dict[str, Any]:
        """Compute metrics for long/short subset in existing output format."""
        if sub_df.empty:
            return {
                "count": 0,
                "win_rate": 0.0,
                "total_pnl": 0.0,
                "avg_pnl": 0.0,
                "profit_factor": "inf",
            }

        basic = cls._compute_basic_metrics(sub_df)
        pf = basic["profit_factor"]
        return {
            "count": int(basic["total_trades"]),
            "win_rate": round(float(basic["win_rate"]) * 100, 2),
            "total_pnl": round(float(basic["total_pnl_abs"]), 2),
            "avg_pnl": round(float(basic["avg_pnl_abs"]), 2),
            "profit_factor": round(float(pf), 2) if pf != float("inf") else "inf",
        }

    def _compute_side_metrics(self, df: pd.DataFrame) -> tuple[dict[str, Any], dict[str, Any]]:
        """Compute metrics separately for long and short trades."""
        long_trades = df[df["is_long"]]
        short_trades = df[np.logical_not(df["is_long"])]
        return (
            self._basic_metrics_for_subset(long_trades),
            self._basic_metrics_for_subset(short_trades),
        )

    def generate(self, risk_free_rate_annual: float = 0.02) -> dict[str, Any]:
        """
        Generates a full set of metrics based on trade history.

        Performs:
        - Win Rate, total, and average profit calculation
        - Profit Factor calculation
        - Daily/weekly/monthly return analysis
        - Exit reason distribution analysis
        - Capital curve construction
        - Max Drawdown calculation
        - Sharpe ratio (annualized, from monthly returns)
        - Average trade duration calculation
        - Separate analysis for long and short positions

        Parameters
        ----------
        risk_free_rate_annual : float, optional
            Annual risk-free rate in decimal for Sharpe ratio (e.g. 0.02 for 2%).
            Default 0.02.

        Returns
        -------
        Dict[str, Any]
            Dictionary of metrics:
            - total_trades: int
            - win_rate: float (%)
            - total_pnl_abs: float ($)
            - total_return_pct: float (%)
            - avg_pnl_abs: float ($)
            - avg_win: float ($)
            - avg_loss: float ($)
            - profit_factor: float or "inf"
            - daily_pnl_mean: float ($)
            - weekly_pnl_mean: float ($)
            - monthly_pnl_mean: float ($)
            - max_drawdown: float (%) — worst drop below window-start capital at
              closed-trade exits; 0 if equity never fell below start
            - sharpe_ratio: float - annualized Sharpe (monthly returns, default RFR 2%)
            - avg_holding_bars: float - average number of bars
            - exit_distribution: dict - {reason: count}
            - initial_capital: float
            - final_capital: float
            - monthly_returns_pct: dict - {YYYY-MM: X.XX%}
            - long_metrics: dict - metrics for long trades
            - short_metrics: dict - metrics for short trades
        """
        self.metrics = {}
        if self.trades.empty:
            self._logger.warning("No trades to analyze. Returning empty metrics.")
            self.metrics = {"error": "no_trades", "total_trades": 0}
            return self.metrics

        df = self._prepare_trades_df()

        closed_df = self._closed_trades_df(df)
        total_entries = int(len(df))
        closed_trades = int(len(closed_df))
        open_trades = total_entries - closed_trades
        basic = self._compute_basic_metrics(closed_df)
        period_means = self._compute_period_pnl_means(closed_df)
        exit_counts = self._compute_exit_distribution(df)
        initial_capital = float(pd.to_numeric(df["capital_before"], errors="coerce").iloc[0])
        if closed_df.empty:
            final_capital = initial_capital
            total_return_pct = 0.0
            drawdown_metrics = {"max_drawdown": 0.0}
            sharpe_ratio = 0.0
            monthly_returns_pct = {}
        else:
            (
                equity_curve,
                initial_capital,
                final_capital,
                total_return_pct,
            ) = self._compute_equity_curve(closed_df)
            drawdown_metrics = self._compute_drawdown_metrics(equity_curve, initial_capital)
            sharpe_ratio = self._compute_sharpe_ratio(
                equity_curve, initial_capital, risk_free_rate_annual
            )
            monthly_returns_pct = self._compute_monthly_returns_pct(
                equity_curve,
                initial_capital,
                closed_df,
            )
        banked_profit = 0.0
        capital_sweep_total = 0.0
        if "banked_profit_after" in df.columns:
            banked_values = pd.to_numeric(df["banked_profit_after"], errors="coerce").dropna()
            if len(banked_values):
                banked_profit = float(banked_values.iloc[-1])
        if "capital_sweep_amount" in df.columns:
            capital_sweep_total = float(
                pd.to_numeric(df["capital_sweep_amount"], errors="coerce").fillna(0.0).sum()
            )
        total_account_value = final_capital + banked_profit
        if banked_profit:
            total_return_pct = ((total_account_value - initial_capital) / initial_capital) * 100
        avg_holding_bars = float(closed_df["holding_bars"].mean()) if not closed_df.empty else 0.0
        long_metrics, short_metrics = self._compute_side_metrics(closed_df)

        # Build the public metrics payload.
        self.metrics = {
            "total_trades": total_entries,
            "closed_trades": closed_trades,
            "open_trades": open_trades,
            "win_rate": round(float(basic["win_rate"]) * 100, 2),
            "total_pnl_abs": round(float(basic["total_pnl_abs"]), 2),
            "total_return_pct": round(total_return_pct, 2),
            "avg_pnl_abs": round(float(basic["avg_pnl_abs"]), 2),
            "avg_win": round(float(basic["avg_win"]), 2),
            "avg_loss": round(float(basic["avg_loss"]), 2),
            "profit_factor": round(float(basic["profit_factor"]), 2)
            if basic["profit_factor"] != float("inf")
            else "inf",
            "daily_pnl_mean": round(float(period_means["daily_pnl_mean"]), 2),
            "weekly_pnl_mean": round(float(period_means["weekly_pnl_mean"]), 2),
            "monthly_pnl_mean": round(float(period_means["monthly_pnl_mean"]), 2),
            "max_drawdown": round(float(drawdown_metrics["max_drawdown"]) * 100, 2),
            "sharpe_ratio": sharpe_ratio,
            "avg_holding_bars": round(avg_holding_bars, 1),
            "exit_distribution": exit_counts,
            "initial_capital": initial_capital,
            "final_capital": round(final_capital, 2),
            "banked_profit": round(banked_profit, 2),
            "capital_sweep_total": round(capital_sweep_total, 2),
            "total_account_value": round(total_account_value, 2),
            "monthly_returns_pct": monthly_returns_pct,
            "long_metrics": long_metrics,
            "short_metrics": short_metrics,
        }

        return self.metrics

    def print_report(self):
        """
        Prints a formatted text report to the console.

        Outputs:
        - Key metrics
        - Periodic returns
        - Exit reason distribution
        - Long/Short breakdown
        """
        if not self.metrics:
            sys.stdout.write("Run .generate() first\n")
            return

        m = self.metrics
        if m.get("error") == "no_trades":
            sys.stdout.write("\n" + "=" * 50 + "\n")
            sys.stdout.write("📊 BACKTEST RESULTS\n")
            sys.stdout.write("=" * 50 + "\n")
            sys.stdout.write("No trades generated.\n")
            sys.stdout.write("=" * 50 + "\n")
            return

        sys.stdout.write("\n" + "=" * 50 + "\n")
        sys.stdout.write("📊 BACKTEST RESULTS\n")
        sys.stdout.write("=" * 50 + "\n")
        sys.stdout.write(f"Initial Capital:    ${m['initial_capital']}\n")
        sys.stdout.write(f"Final Capital:      ${m['final_capital']}\n")
        if m.get("banked_profit", 0):
            sys.stdout.write(f"Banked Profit:      ${m['banked_profit']}\n")
            sys.stdout.write(f"Total Account:      ${m['total_account_value']}\n")
        sys.stdout.write(f"Total Return:       {m['total_return_pct']}%\n")
        sys.stdout.write(f"Total PnL:          ${m['total_pnl_abs']}\n")
        sys.stdout.write(f"Win Rate:           {m['win_rate']}%\n")
        sys.stdout.write(f"Profit Factor:      {m['profit_factor']}\n")
        sys.stdout.write(f"Max Drawdown:       {m['max_drawdown']}%\n")
        sys.stdout.write(f"Avg. Trade:         ${m['avg_pnl_abs']}\n")
        sys.stdout.write(f"Avg. Win:           ${m['avg_win']}\n")
        sys.stdout.write(f"Avg. Loss:          ${m['avg_loss']}\n")
        sys.stdout.write(f"Avg. Duration:      {m['avg_holding_bars']} bars\n")

        sys.stdout.write("\nReturns:\n")
        sys.stdout.write(f"  Daily:   ${m['daily_pnl_mean']}\n")
        sys.stdout.write(f"  Weekly:  ${m['weekly_pnl_mean']}\n")
        sys.stdout.write(f"  Monthly: ${m['monthly_pnl_mean']}\n")

        sys.stdout.write("\nExit Distribution:\n")
        for reason, count in m["exit_distribution"].items():
            sys.stdout.write(f"  {reason}: {count}\n")

        # === Long/Short Analysis ===
        sys.stdout.write("\n" + "-" * 40 + "\n")
        sys.stdout.write("📈 LONG POSITIONS\n")
        sys.stdout.write("-" * 40 + "\n")
        lm = m["long_metrics"]
        sys.stdout.write(f"  Count:      {lm['count']}\n")
        sys.stdout.write(f"  Win Rate:   {lm['win_rate']}%\n")
        sys.stdout.write(f"  Total PnL:  ${lm['total_pnl']}\n")
        sys.stdout.write(f"  Avg PnL:    ${lm['avg_pnl']}\n")
        sys.stdout.write(f"  PF:         {lm['profit_factor']}\n")

        sys.stdout.write("\n" + "-" * 40 + "\n")
        sys.stdout.write("📉 SHORT POSITIONS\n")
        sys.stdout.write("-" * 40 + "\n")
        sm = m["short_metrics"]
        sys.stdout.write(f"  Count:      {sm['count']}\n")
        sys.stdout.write(f"  Win Rate:   {sm['win_rate']}%\n")
        sys.stdout.write(f"  Total PnL:  ${sm['total_pnl']}\n")
        sys.stdout.write(f"  Avg PnL:    ${sm['avg_pnl']}\n")
        sys.stdout.write(f"  PF:         {sm['profit_factor']}\n")

        # === Monthly Returns ===
        sys.stdout.write("\n" + "-" * 40 + "\n")
        sys.stdout.write("📅 Monthly Returns (%)\n")
        sys.stdout.write("-" * 40 + "\n")
        if m["monthly_returns_pct"]:
            sys.stdout.write(
                f"{'Month':<10} {'Return (%)':<15} {'Return ABS (%)':<15} {'Withdrawn ($)':<15}\n"
            )
            sys.stdout.write("-" * 60 + "\n")
            for month, rets in m["monthly_returns_pct"].items():
                ret, ret_abs = rets["ret"], rets["ret_abs"]
                withdrawn = rets.get("withdrawn", 0.0)
                sign = "+" if ret >= 0 else ""
                sign_abs = "+" if ret_abs >= 0 else ""
                sys.stdout.write(
                    f"{month:<10} {sign}{ret:<14} {sign_abs}{ret_abs:<14} ${withdrawn:<14}\n"
                )
        else:
            sys.stdout.write("  No data\n")

        sys.stdout.write("=" * 50 + "\n")

    def export_results(
        self,
        folder: str = "results",
        ohlcv_df: pd.DataFrame | None = None,
        bars_before: int = 20,
        bars_after: int = 10,
    ):
        """
        Exports analysis results to CSV files.

        Creates:
        - {folder}/trades.csv - full trade history (with is_long)
        - {folder}/metrics.csv - summary metrics (one row)
        - {folder}/trade_diagnostics.csv - compact exit/side/SL-distance
          diagnostics when trades exist
        - {folder}/ohlcv.csv - full OHLCV frame used by the run, when provided
        - {folder}/trade_chart.html - interactive TradingView chart report,
          when OHLCV is provided
        - {folder}/equity_curve.csv - capital curve (time → capital)
        - {folder}/trade_candles/trade_000.csv, ... - OHLCV slices per trade
          (only when ohlcv_df is provided and trades are non-empty)

        Parameters
        ----------
        folder : str
            Output directory.
        ohlcv_df : pd.DataFrame | None
            OHLCV data (DatetimeIndex) used for the backtest. When provided,
            saves a candle slice around each trade for charting.
        bars_before : int
            Number of bars before entry to include in each trade slice.
        bars_after : int
            Number of bars after exit to include in each trade slice.
        """
        os.makedirs(folder, exist_ok=True)
        trades_path = os.path.join(folder, "trades.csv")
        self.trades.to_csv(trades_path, index=False)
        self._logger.info("Trades saved: %s", trades_path)

        metrics_df = pd.DataFrame([self.metrics])
        metrics_path = os.path.join(folder, "metrics.csv")
        metrics_df.to_csv(metrics_path, index=False)
        self._logger.info("Metrics saved: %s", metrics_path)

        if not self.trades.empty:
            trade_diagnostics = self._trade_diagnostics()
            diagnostics_path = os.path.join(folder, "trade_diagnostics.csv")
            trade_diagnostics.to_csv(diagnostics_path, index=False)
            self._logger.info("Trade diagnostics saved: %s", diagnostics_path)

        if not self.signals.empty:
            signals_path = os.path.join(folder, "signals.csv")
            self.signals.to_csv(signals_path, index=True)
            self._logger.info("Signals saved: %s", signals_path)

            diagnostics = self._signal_diagnostics()
            diagnostics_path = os.path.join(folder, "signal_diagnostics.csv")
            diagnostics.to_csv(diagnostics_path, index=False)
            self._logger.info("Signal diagnostics saved: %s", diagnostics_path)

        if self.equity_curve is not None:
            equity_path = os.path.join(folder, "equity_curve.csv")
            self.equity_curve.to_csv(equity_path, header=True)
            self._logger.info("Equity curve saved: %s", equity_path)

        if ohlcv_df is not None:
            self._export_full_ohlcv(ohlcv_df=ohlcv_df, folder=folder)
            self._export_trade_chart(ohlcv_df=ohlcv_df, folder=folder)

        if ohlcv_df is not None and not self.trades.empty:
            self._export_trade_candles(
                ohlcv_df=ohlcv_df,
                folder=folder,
                bars_before=bars_before,
                bars_after=bars_after,
            )

        # Save entry metrics when trade-condition analysis was run.
        if self.trade_analyzer is not None:
            self.trade_analyzer.save_entry_metrics(folder)

    def _export_full_ohlcv(self, *, ohlcv_df: pd.DataFrame, folder: str) -> None:
        """Save the continuous OHLCV frame used by the chart report."""
        ohlc_cols = [c for c in ("open", "high", "low", "close") if c in ohlcv_df.columns]
        if len(ohlc_cols) < 4:
            self._logger.warning("No complete OHLC columns in ohlcv_df; skipping ohlcv.csv")
            return
        cols = ohlc_cols + (["volume"] if "volume" in ohlcv_df.columns else [])
        frame = ohlcv_df[cols].copy()
        frame.index.name = frame.index.name or "timestamp"
        path = os.path.join(folder, "ohlcv.csv")
        frame.to_csv(path)
        self._logger.info("Full OHLCV saved: %s", path)

    def _export_trade_chart(self, *, ohlcv_df: pd.DataFrame, folder: str) -> None:
        """Save the default interactive TradingView report for this run."""
        try:
            path = build_trade_chart_report(
                TradeChartReportConfig(
                    run_dir=Path(folder),
                    ohlcv_df=ohlcv_df,
                )
            )
        except (FileNotFoundError, ValueError) as exc:
            self._logger.warning("Trade chart export skipped: %s", exc)
            return
        self._logger.info("Trade chart saved: %s", path)

    def _export_trade_candles(
        self,
        *,
        ohlcv_df: pd.DataFrame,
        folder: str,
        bars_before: int,
        bars_after: int,
    ) -> None:
        """Save OHLCV slice around each trade for charting."""
        trades = self._closed_trades_df(self.trades.copy())
        if trades.empty:
            self._logger.info("No closed trades; skipping trade_candles export")
            return
        trades["entry_time"] = pd.to_datetime(trades["entry_time"])
        trades["exit_time"] = pd.to_datetime(trades["exit_time"])

        if "exit_bar_index" not in trades.columns:
            # Backfill for older backtest runs: infer exit bar from exit_time
            ohlcv_index = ohlcv_df.index
            if not isinstance(ohlcv_index, pd.DatetimeIndex):
                self._logger.warning(
                    "OHLCV index is not DatetimeIndex; skipping trade_candles export"
                )
                return
            exit_bar_indices = []
            for et in trades["exit_time"]:
                pos = ohlcv_index.get_indexer([et], method="nearest")[0]
                if pos < 0:
                    pos = 0
                elif pos >= len(ohlcv_df):
                    pos = len(ohlcv_df) - 1
                exit_bar_indices.append(pos)
            trades["exit_bar_index"] = exit_bar_indices
        if "entry_bar_index" not in trades.columns:
            self._logger.warning("entry_bar_index missing in trades; skipping trade_candles export")
            return

        ohlc_cols = [c for c in ("open", "high", "low", "close") if c in ohlcv_df.columns]
        if "volume" in ohlcv_df.columns:
            ohlc_cols = ohlc_cols + ["volume"]
        if not ohlc_cols:
            self._logger.warning("No OHLC(V) columns in ohlcv_df; skipping trade_candles")
            return

        candles_dir = os.path.join(folder, "trade_candles")
        os.makedirs(candles_dir, exist_ok=True)
        n_bars = len(ohlcv_df)

        for i in range(len(trades)):
            row = trades.iloc[i]
            entry_bar = int(row["entry_bar_index"])
            exit_bar = int(row["exit_bar_index"])
            start = max(0, entry_bar - bars_before)
            end = min(n_bars, exit_bar + bars_after + 1)
            if start >= end:
                self._logger.debug(
                    "Trade %d: invalid range start=%s end=%s, skipping",
                    i,
                    start,
                    end,
                )
                continue
            slice_df = ohlcv_df.iloc[start:end][ohlc_cols].copy()
            slice_df.index.name = "timestamp"
            out_path = os.path.join(candles_dir, f"trade_{i:03d}.csv")
            slice_df.to_csv(out_path)

        self._logger.info("Trade candles saved: %s (%d files)", candles_dir, len(trades))

    def _signal_diagnostics(self) -> pd.DataFrame:
        """Return compact signal/verdict counts for no-trade smoke analysis."""
        rows: list[dict[str, Any]] = [
            {"metric": "rows", "bucket": "all", "value": len(self.signals)}
        ]

        for col in ("signal", "decision", "regime"):
            if col not in self.signals.columns:
                continue
            counts = self.signals[col].value_counts(dropna=False).sort_index()
            rows.extend(
                {
                    "metric": f"{col}_count",
                    "bucket": str(bucket),
                    "value": int(value),
                }
                for bucket, value in counts.items()
            )

        if "confidence" in self.signals.columns:
            confidence = pd.to_numeric(self.signals["confidence"], errors="coerce")
            valid_confidence = confidence.dropna()
            rows.extend(
                [
                    {
                        "metric": "confidence",
                        "bucket": "max",
                        "value": float(valid_confidence.max())
                        if not valid_confidence.empty
                        else 0.0,
                    },
                    {
                        "metric": "confidence",
                        "bucket": "mean",
                        "value": float(valid_confidence.mean())
                        if not valid_confidence.empty
                        else 0.0,
                    },
                ]
            )
            if not valid_confidence.empty:
                rows.extend(
                    {
                        "metric": "confidence_quantile",
                        "bucket": f"p{int(q * 100)}",
                        "value": float(valid_confidence.quantile(q)),
                    }
                    for q in (0.5, 0.75, 0.9, 0.95, 0.99)
                )

        return pd.DataFrame(rows)

    def _trade_diagnostics(self) -> pd.DataFrame:
        """Return compact trade diagnostics for exit-quality smoke analysis."""
        if self.trades.empty:
            return pd.DataFrame(columns=["section", "group", "metric", "value"])

        df = self.trades.copy()
        rows: list[dict[str, Any]] = []

        def add(section: str, group: str, metric: str, value: Any) -> None:
            if isinstance(value, np.generic):
                value = value.item()
            rows.append(
                {
                    "section": section,
                    "group": group,
                    "metric": metric,
                    "value": value,
                }
            )

        total_trades = len(df)
        add("summary", "all", "trades", int(total_trades))

        closed_df = self._closed_trades_df(df)
        add("summary", "all", "closed_trades", int(len(closed_df)))
        add("summary", "all", "open_trades", int(total_trades - len(closed_df)))

        if "entry_time" in closed_df.columns and "exit_time" in closed_df.columns:
            entry_time = pd.to_datetime(closed_df["entry_time"], errors="coerce")
            exit_time = pd.to_datetime(closed_df["exit_time"], errors="coerce")
            duration_hours = ((exit_time - entry_time).dt.total_seconds() / 3600).dropna()
            if not duration_hours.empty:
                add("summary", "all", "duration_hours_mean", duration_hours.mean())
                add("summary", "all", "duration_hours_p50", duration_hours.quantile(0.5))
                add("summary", "all", "duration_hours_p95", duration_hours.quantile(0.95))

            span_days = (
                (entry_time.max() - entry_time.min()).total_seconds() / 86400
                if entry_time.notna().sum() > 1
                else 0.0
            )
            if span_days > 0:
                add("summary", "all", "trades_per_day", total_trades / span_days)

        if "exit_reason" in df.columns:
            counts = df["exit_reason"].value_counts(dropna=False).sort_index()
            for reason, count in counts.items():
                group = str(reason)
                add("exit_reason", group, "count", int(count))
                add("exit_reason", group, "share", float(count) / total_trades)

        if {"is_long", "exit_reason"}.issubset(df.columns):
            side = df["is_long"].map({True: "long", False: "short"})
            side_reason_counts = (
                df.assign(side=side)
                .groupby(["side", "exit_reason"], dropna=False)
                .size()
                .sort_index()
            )
            for (side_name, reason), count in side_reason_counts.items():
                add("side_exit_reason", f"{side_name}:{reason}", "count", int(count))

        if {"is_long", "pnl_abs"}.issubset(closed_df.columns):
            side = closed_df["is_long"].map({True: "long", False: "short"})
            pnl_by_side = (
                closed_df.assign(side=side)
                .groupby("side", dropna=False)["pnl_abs"]
                .agg(["count", "sum", "mean", "median"])
                .sort_index()
            )
            for side_name, stats in pnl_by_side.iterrows():
                for metric, value in stats.items():
                    add("side_pnl", str(side_name), str(metric), value)

        if {"exit_reason", "pnl_abs"}.issubset(closed_df.columns):
            pnl_by_reason = (
                closed_df.groupby("exit_reason", dropna=False)["pnl_abs"]
                .agg(["count", "sum", "mean", "median"])
                .sort_index()
            )
            for reason, stats in pnl_by_reason.iterrows():
                for metric, value in stats.items():
                    add("exit_reason_pnl", str(reason), str(metric), value)

        if "open_positions_before" in df.columns:
            open_positions_before = pd.to_numeric(
                df["open_positions_before"], errors="coerce"
            ).dropna()
            if not open_positions_before.empty:
                add(
                    "margin",
                    "all",
                    "peak_open_positions",
                    int(open_positions_before.max()) + 1,
                )

        if "total_locked_margin_after_entry" in df.columns:
            locked_after_entry = pd.to_numeric(
                df["total_locked_margin_after_entry"], errors="coerce"
            )
        elif {"total_locked_margin_before", "locked_margin"}.issubset(df.columns):
            locked_after_entry = pd.to_numeric(
                df["total_locked_margin_before"], errors="coerce"
            ).fillna(0.0) + pd.to_numeric(df["locked_margin"], errors="coerce").fillna(0.0)
        else:
            locked_after_entry = pd.to_numeric(
                df.get("locked_margin", pd.Series(index=df.index, dtype="float64")),
                errors="coerce",
            )

        valid_locked_after_entry = locked_after_entry.dropna()
        if not valid_locked_after_entry.empty:
            peak_locked = float(valid_locked_after_entry.max())
            add("margin", "all", "peak_locked_margin", peak_locked)
            initial_capital = (
                float(pd.to_numeric(df["capital_before"], errors="coerce").iloc[0])
                if "capital_before" in df.columns and len(df) > 0
                else 0.0
            )
            if initial_capital > 0:
                add(
                    "margin",
                    "all",
                    "peak_locked_margin_pct_initial",
                    peak_locked / initial_capital * 100,
                )

        if "available_balance_before" in df.columns:
            available_before = pd.to_numeric(
                df["available_balance_before"], errors="coerce"
            ).dropna()
            if not available_before.empty:
                add(
                    "margin",
                    "all",
                    "min_available_balance_before",
                    float(available_before.min()),
                )

        if {"exit_reason", "sl_distance_atr"}.issubset(df.columns):
            sl_distance = pd.to_numeric(df["sl_distance_atr"], errors="coerce")
            for reason, values in sl_distance.groupby(df["exit_reason"], dropna=False):
                valid = values.dropna()
                if valid.empty:
                    continue
                for metric, value in {
                    "count": int(valid.count()),
                    "mean": valid.mean(),
                    "p50": valid.quantile(0.5),
                    "p75": valid.quantile(0.75),
                    "p90": valid.quantile(0.9),
                    "p95": valid.quantile(0.95),
                    "max": valid.max(),
                }.items():
                    add("sl_distance_atr_by_exit", str(reason), metric, value)

        if {"sl_anchor_type", "sl_distance_atr"}.issubset(df.columns):
            sl_distance = pd.to_numeric(df["sl_distance_atr"], errors="coerce")
            grouped = sl_distance.groupby(df["sl_anchor_type"], dropna=False)
            for anchor_type, values in grouped:
                valid = values.dropna()
                if valid.empty:
                    continue
                add("sl_anchor", str(anchor_type), "count", int(valid.count()))
                add("sl_anchor", str(anchor_type), "distance_atr_mean", valid.mean())
                add("sl_anchor", str(anchor_type), "distance_atr_p50", valid.quantile(0.5))
                add("sl_anchor", str(anchor_type), "distance_atr_p95", valid.quantile(0.95))

        return pd.DataFrame(rows)

